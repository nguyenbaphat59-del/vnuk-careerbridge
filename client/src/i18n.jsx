function translateGenerated(text, lang) {
  if (lang !== 'vi' || typeof text !== 'string') return text;
  if (generatedVi[text]) return generatedVi[text];
  let match = text.match(/^(\d+) areas to prioritise before applying$/);
  if (match) return `Có ${match[1]} nhóm kỹ năng cần ưu tiên trước khi ứng tuyển`;
  if (text === 'Build proof of your skills and keep practising') return 'Tạo minh chứng cho kỹ năng và tiếp tục luyện tập';
  match = text.match(/^Your profile already mentions (.+), so you can build on that foundation\.$/);
  if (match) return `Hồ sơ của bạn đã đề cập đến ${generatedVi[match[1]] || match[1]}, đây là nền tảng để bạn tiếp tục phát triển.`;
  match = text.match(/^(.+) needs more visible evidence through practice or a small project\.$/);
  if (match) return `${generatedVi[match[1]] || match[1]} cần được thể hiện rõ hơn qua thực hành hoặc một dự án nhỏ.`;
  match = text.match(/^Spend a focused session building confidence in (.+)\.$/);
  if (match) return `Dành một phiên tập trung để củng cố sự tự tin với ${generatedVi[match[1]] || match[1]}.`;
  match = text.match(/^This demo analysis compares your profile( and the job description)? with common expectations for (.+)\. It is a starting point, not a hiring prediction\.$/);
  if (match) return `Bản phân tích demo đối chiếu hồ sơ${match[1] ? ' và mô tả công việc' : ''} của bạn với kỳ vọng phổ biến cho ${match[2]}. Đây là điểm khởi đầu, không phải dự đoán tuyển dụng.`;
  match = text.match(/^The job description mentions (.+); compare these with your current evidence\.$/);
  if (match) return `Mô tả công việc đề cập đến ${match[1]}; hãy đối chiếu với minh chứng kỹ năng hiện có.`;
  if (text.startsWith('You have a starting direction')) return 'Bạn đã xác định được hướng đi ban đầu; lộ trình sẽ chuyển hướng đó thành các bước thực hành cụ thể.';
  if (text.startsWith('Your interests (')) return 'Sở thích của bạn có thể giúp việc luyện tập sát với mối quan tâm cá nhân hơn.';
  if (text === 'You are willing to map your current level before choosing what to learn next.') return 'Bạn đang chủ động xác định trình độ hiện tại trước khi chọn nội dung cần học tiếp.';
  match = text.match(/^Practise one focused (.+) concept$/);
  if (match) return `Luyện tập một khái niệm trọng tâm về ${generatedVi[match[1]] || match[1]}`;
  match = text.match(/^Apply (.+) in a short exercise$/);
  if (match) return `Vận dụng ${generatedVi[match[1]] || match[1]} trong một bài tập ngắn`;
  match = text.match(/^Review and improve your (.+) work$/);
  if (match) return `Ôn tập và cải thiện phần thực hành ${generatedVi[match[1]] || match[1]}`;
  if (text.startsWith('A practical path toward')) return text;
  return text;
}

const LanguageContext = createContext(null);
export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('internpath_language') || 'en');
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const changeLanguage = (next) => { localStorage.setItem('internpath_language', next); setLang(next); document.documentElement.lang = next; };
  const value = useMemo(() => ({ lang, setLanguage: changeLanguage, t: (text) => translateGenerated(translations[lang]?.[text] || text, lang) }), [lang]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}
export function LanguageSwitch({ compact = false }) {
  const { lang, setLanguage, t } = useLanguage();
  return <div className={`language-switch ${compact ? 'language-switch-compact' : ''}`} aria-label={t('Language')}>
    <Languages size={14} aria-hidden="true" />
    <button type="button" className={lang === 'vi' ? 'selected' : ''} aria-pressed={lang === 'vi'} onClick={() => setLanguage('vi')}>VI</button>
    <button type="button" className={lang === 'en' ? 'selected' : ''} aria-pressed={lang === 'en'} onClick={() => setLanguage('en')}>EN</button>
  </div>;
}
